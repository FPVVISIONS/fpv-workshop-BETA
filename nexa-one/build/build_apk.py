#!/usr/bin/env python3
"""Rebuild the NEXA ONE APK with the NEXA FX layer.

  python build_apk.py --apk NEXA-ONE.apk --keystore release.p12 \
      --storepass-file release.pass --out NEXA-ONE-fx.apk

Steps: inject web/ files + bundle patches → strip old signature → zipalign
→ v1 (jarsigner, needed for minSdk 23) → re-align → v2 signature.
Needs: Python `cryptography`, a JDK (jarsigner) on PATH.
"""
import argparse
import fnmatch
import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from cryptography.hazmat.primitives.serialization import Encoding, pkcs12  # noqa: E402

from apksign_v2 import sign_v2  # noqa: E402
from apkzip import make_entry, read_entries, write_zip  # noqa: E402

WEB = os.path.join(HERE, "..", "web")
PUBLIC = "assets/public/"
SIG_FILES = ("META-INF/MANIFEST.MF", "META-INF/*.SF", "META-INF/*.RSA", "META-INF/*.DSA", "META-INF/*.EC")

# Source-level edits to the compiled bundle. Each must match exactly once.
BUNDLE_PATCHES = [
    # Screen transitions: the outgoing screen used the same slow spring as the
    # incoming one, and AnimatePresence(mode="wait") waits for it (~370 ms).
    # A quick 160 ms ease-in exit makes tab switches feel ~40% snappier.
    (
        'exit:e=>({opacity:0,x:e===0?0:e>0?18:-18})',
        'exit:e=>({opacity:0,x:e===0?0:e>0?18:-18,transition:{duration:.16,ease:[.4,0,1,1]}})',
    ),
    # The original preferences sheet said "local profile — no account needed",
    # which contradicts the new accounts layer (nexa-auth.js). Reword it.
    (
        'children:n.name||"פרופיל מקומי"',
        'children:n.name||"העדפות אפליקציה"',
    ),
    (
        'children:"נשמר רק במכשיר הזה. אין צורך בחשבון."',
        'children:"ההעדפות נשמרות במכשיר הזה. את החשבון מנהלים ממסך החשבון."',
    ),
]


def patch_bundle(src: bytes) -> bytes:
    text = src.decode("utf-8")
    for old, new in BUNDLE_PATCHES:
        n = text.count(old)
        if n != 1:
            raise SystemExit(f"bundle patch target found {n}x (expected 1): {old[:60]}…")
        text = text.replace(old, new)
    return text.encode("utf-8")


WEB_EXTRAS = ("nexa-fx.css", "nexa-fx.js", "nexa-auth.css", "nexa-auth.js", "nexa-guide.css", "nexa-guide.js", "nexa-guide-bottle.svg",
              "nexa-config.js", "nexa-supabase.js")
ICONS = os.path.join(HERE, "..", "icon", "out")  # rendered by icon/render.js


def icon_overrides():
    """APK path -> bytes for every rendered icon/splash asset that replaces an
    existing entry (paths under icon/out mirror the APK layout)."""
    out = {}
    for root, _, files in os.walk(ICONS):
        for f in files:
            full = os.path.join(root, f)
            rel = os.path.relpath(full, ICONS).replace(os.sep, "/")
            if not rel.startswith("preview/"):
                out[rel] = open(full, "rb").read()
    return out


def inject(entries, supabase=None):
    out, names = [], {e.name for e in entries}
    web_files = {f: open(os.path.join(WEB, f), "rb").read() for f in ("index.html",) + WEB_EXTRAS}
    if supabase:
        url, key = supabase
        if not url.startswith("https://") or key.count(".") != 2:
            raise SystemExit("supabase: need an https:// project URL and the public anon key (a JWT with two dots). "
                             "Never use the service_role key in an app.")
        try:                                           # a real service_role key says so inside its payload
            import base64
            payload = key.split(".")[1]
            role = json.loads(base64.urlsafe_b64decode(payload + "=" * (-len(payload) % 4))).get("role")
        except Exception:
            role = None                                # can't decode (e.g. a test key): accept
        if role == "service_role" or "service_role" in key:
            raise SystemExit("That is the service_role (secret) key. Anything in the app can be extracted, "
                             "so use the public anon key instead.")
        cfg = ("/* generated by build_apk.py */\nwindow.NEXA_SUPABASE = %s;\n"
               % json.dumps({"url": url.rstrip("/"), "anonKey": key}))
        web_files["nexa-config.js"] = cfg.encode("utf-8")
    icons = icon_overrides()
    missing = sorted(set(icons) - names)
    if missing:
        raise SystemExit(f"icon assets with no matching APK entry: {missing}")
    for e in entries:
        if any(fnmatch.fnmatch(e.name, p) for p in SIG_FILES):
            continue
        if e.name in icons:
            out.append(make_entry(e.name, icons[e.name], like=e))
            continue
        if e.name == PUBLIC + "index.html":
            out.append(make_entry(e.name, web_files["index.html"], like=e))
            for extra in WEB_EXTRAS:
                if PUBLIC + extra not in names:
                    out.append(make_entry(PUBLIC + extra, web_files[extra], like=e))
            continue
        if e.name in tuple(PUBLIC + x for x in WEB_EXTRAS):
            out.append(make_entry(e.name, web_files[e.name[len(PUBLIC):]], like=e))
            continue
        if fnmatch.fnmatch(e.name, PUBLIC + "assets/index-*.js"):
            import zlib
            raw = e.data if e.method == 0 else zlib.decompress(e.data, -15)
            out.append(make_entry(e.name, patch_bundle(raw), like=e))
            continue
        out.append(e)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apk", required=True)
    ap.add_argument("--keystore", required=True, help="PKCS#12 keystore")
    ap.add_argument("--alias", default="nexa")
    ap.add_argument("--storepass-file", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--supabase-url", help="https://<project>.supabase.co (turns on real accounts)")
    ap.add_argument("--supabase-anon-key", help="the PUBLIC anon key; never the service_role key")
    a = ap.parse_args()

    password = open(a.storepass_file).read().strip()
    key, cert, _ = pkcs12.load_key_and_certificates(open(a.keystore, "rb").read(), password.encode())

    supabase = (a.supabase_url, a.supabase_anon_key) if (a.supabase_url or a.supabase_anon_key) else None
    if supabase and not all(supabase):
        raise SystemExit("give both --supabase-url and --supabase-anon-key")
    entries = inject(read_entries(open(a.apk, "rb").read()), supabase)
    with tempfile.TemporaryDirectory() as td:
        unsigned, v1 = os.path.join(td, "unsigned.apk"), os.path.join(td, "v1.apk")
        open(unsigned, "wb").write(write_zip(entries))
        subprocess.run(
            ["jarsigner", "-keystore", a.keystore, "-storetype", "PKCS12", "-storepass:file", a.storepass_file,
             "-digestalg", "SHA-256", "-sigalg", "SHA256withRSA", "-sigfile", "CERT",
             "-signedjar", v1, unsigned, a.alias],
            check=True, stdout=subprocess.DEVNULL)
        aligned = write_zip(read_entries(open(v1, "rb").read()))
    signed = sign_v2(aligned, key, cert.public_bytes(Encoding.DER))
    open(a.out, "wb").write(signed)
    print(f"wrote {a.out} ({len(signed):,} bytes)")


if __name__ == "__main__":
    main()
